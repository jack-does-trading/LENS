"""Does the website's benchmarks page still tell the truth?

`frontend/app/benchmarks.json` is a committed snapshot, generated by
scripts/export_benchmarks.py and imported by /benchmarks at build time. That is
the right shape for the data -- computing it needs a seeded Postgres, and the
page would otherwise hand a visitor a free-tier cold start for numbers that only
change when someone commits.

The risk it buys is the obvious one: a snapshot is a copy, and a copy goes stale
silently. A benchmarks page quoting figures the gates no longer produce is worse
than having no benchmarks page at all, because it is a public claim rather than
an internal one. So this recomputes every published figure from the same harness
the floors run through, and fails if the file disagrees.

Marked `eval`, so it runs in the same no-secrets PR gate that enforces the
thresholds. If you change retrieval, the judge rubric or a threshold, this test
fails until you re-export -- which is the intended workflow, not an obstacle.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from sqlalchemy.orm import Session

from eval.cassettes import load_corpus
from eval.harness import load_thresholds, seed_corpus
from scripts import export_benchmarks

pytestmark = pytest.mark.eval

SNAPSHOT_PATH = Path(export_benchmarks.OUT_PATH)


@pytest.fixture(scope="module")
def snapshot() -> dict:
    assert SNAPSHOT_PATH.exists(), (
        f"{SNAPSHOT_PATH} is missing; the /benchmarks page imports it. "
        "Generate it with scripts/export_benchmarks.py."
    )
    return json.loads(SNAPSHOT_PATH.read_text())


@pytest.fixture
def seeded(db_session: Session) -> Session:
    seed_corpus(db_session, load_corpus())
    db_session.flush()
    return db_session


def test_the_published_retrieval_numbers_are_the_ones_the_harness_produces(
    snapshot: dict, seeded: Session
) -> None:
    """The load-bearing assertion. Every number a visitor reads on /benchmarks,
    recomputed from the cassette and compared to the committed file."""
    fresh = export_benchmarks.retrieval_section(seeded)
    published = {m["key"]: m for m in snapshot["retrieval"]["metrics"]}
    computed = {m["key"]: m for m in fresh["metrics"]}

    assert published.keys() == computed.keys(), "the published metric set has drifted"
    for key, pub in published.items():
        got = computed[key]
        assert pub["now"] == pytest.approx(got["now"], abs=1e-3), (
            f"/benchmarks publishes {key}={pub['now']} but the harness now computes "
            f"{got['now']}. Re-run scripts/export_benchmarks.py and commit the result."
        )
        assert pub["before"] == pytest.approx(got["before"], abs=1e-3), (
            f"the published 'before' for {key} no longer matches the golden set's "
            "retrieved_at_export"
        )
        assert pub["floor"] == pytest.approx(got["floor"], abs=1e-9)

    assert snapshot["retrieval"]["top_k"] == fresh["top_k"]
    assert snapshot["retrieval"]["tag_match_weight"] == fresh["tag_match_weight"]


def test_the_published_recall_ceiling_is_present_and_honest(snapshot: dict) -> None:
    """recall@k cannot reach 1.0 when a case expects more principles than k.
    Publishing the value without the ceiling would understate the retriever and
    read as a much worse number than it is, so the ceiling is not optional."""
    recall = next(m for m in snapshot["retrieval"]["metrics"] if m["key"] == "recall_at_k")
    assert "ceiling" in recall, "recall is published without its ceiling"
    assert 0 < recall["ceiling"] < 1.0
    assert recall["now"] <= recall["ceiling"]


def test_the_published_verifier_numbers_match(snapshot: dict) -> None:
    fresh = export_benchmarks.verifier_section()
    for field in ("catch_rate", "caught", "seeded", "false_positive_rate", "clean_cases"):
        assert snapshot["verifier"][field] == fresh[field], field


def test_the_published_kappa_matches_the_recorded_verdicts(snapshot: dict) -> None:
    """If the judge rubric changes, the cassette misses and this fails loudly --
    which is the point. κ is the figure that licenses every faithfulness claim
    on the page, so it may never be a number nobody rechecked."""
    fresh = export_benchmarks.judge_section()
    assert snapshot["judge"]["rubric_version"] == fresh["rubric_version"]
    assert snapshot["judge"]["model"] == fresh["model"]
    published = {f["field"]: f for f in snapshot["judge"]["fields"]}
    computed = {f["field"]: f for f in fresh["fields"]}
    assert published.keys() == computed.keys()
    for field, pub in published.items():
        assert pub["kappa"] == pytest.approx(computed[field]["kappa"], abs=1e-3), field
        assert pub["raw_agreement"] == pytest.approx(
            computed[field]["raw_agreement"], abs=1e-3
        ), field


def test_no_published_metric_sits_below_its_own_floor(snapshot: dict) -> None:
    """A page that shows a green checkmark next to a breached floor is a lie the
    gates cannot catch, because the gates check the code and this checks the copy."""
    for metric in snapshot["retrieval"]["metrics"]:
        assert metric["now"] >= metric["floor"], metric["key"]
    assert snapshot["verifier"]["catch_rate"] >= snapshot["verifier"]["catch_rate_floor"]
    assert (
        snapshot["verifier"]["false_positive_rate"]
        <= snapshot["verifier"]["false_positive_rate_max"]
    )
    floor = snapshot["judge"]["kappa_floor"]
    for field in snapshot["judge"]["fields"]:
        assert field["kappa"] is not None and field["kappa"] >= floor, field["field"]


def test_the_snapshot_declares_that_the_golden_set_is_redacted(snapshot: dict) -> None:
    """Every case on that page is a paraphrase of a real person's journal entry.
    The page says so, and this is what stops a future export quietly publishing
    verbatim text after someone adds an unredacted case."""
    assert snapshot["golden_set"]["all_redacted"] is True
    assert snapshot["golden_set"]["n"] >= 16


def test_thresholds_on_the_page_are_the_thresholds_in_the_repo(snapshot: dict) -> None:
    """The page shows floors as well as values. If a floor moves in
    eval/thresholds.json and the page keeps the old one, the page is claiming a
    stricter gate than actually exists."""
    thresholds = load_thresholds()
    assert snapshot["retrieval"]["top_k"] == thresholds["retrieval"]["top_k"]
    assert snapshot["judge"]["kappa_floor"] == thresholds["judge"]["human_kappa_floor"]
    assert (
        snapshot["verifier"]["catch_rate_floor"] == thresholds["verifier"]["catch_rate_floor"]
    )


def test_the_snapshot_records_where_it_came_from(snapshot: dict) -> None:
    """Numbers without provenance are decoration. A reader needs to know which
    commit and which prompt versions produced them, or a score change is
    unattributable -- the same reason PROMPT_VERSION exists at all."""
    assert snapshot["generated_at"].endswith("Z")
    assert snapshot["commit"], "no commit recorded"
    for stage in ("synthesis", "verification", "judge"):
        assert snapshot["prompt_versions"][stage]


def test_the_published_test_counts_are_not_stale(snapshot: dict) -> None:
    """The likeliest number in the whole file to go quietly wrong, because
    nothing breaks when it does."""
    counts = snapshot.get("tests") or {}
    for marker in ("default", "eval", "eval_live"):
        published = counts.get(marker)
        if published is None:
            pytest.skip("snapshot was exported with --skip-test-counts")
        expr = {
            "default": "not eval and not eval_live",
            "eval": "eval",
            "eval_live": "eval_live",
        }[marker]
        actual = export_benchmarks._collect_count(expr)
        if actual is None:
            pytest.skip("could not collect test counts in this environment")
        assert published == actual, (
            f"/benchmarks publishes {published} {marker} tests; pytest collects {actual}"
        )
