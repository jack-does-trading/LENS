#!/usr/bin/env python3
"""Freeze the eval numbers into a JSON snapshot the website can render.

    python scripts/export_benchmarks.py \
        --database-url postgresql://lens:lens@localhost:5432/lens_bench

Writes `frontend/app/benchmarks.json`, which /benchmarks imports at build time.

**Why a committed snapshot rather than a live API.** The numbers on that page are
produced by seeding 1213 principles into a throwaway Postgres and replaying
recorded vectors. That is a ten-second job, not a request handler, and the
backend it would have to run on is a free-tier Render instance that sleeps after
15 minutes -- so a live endpoint would hand a visitor a 30-second cold start or a
spinner in exchange for numbers that only change when someone commits. Same
reasoning as `frontend/app/bookCatalogFallback.ts`: a point-in-time copy of real
data, generated by a script, reviewable as a diff.

**What stops it going stale.** `tests/test_benchmarks_snapshot.py` recomputes
every figure and fails if the committed file disagrees. A benchmarks page quoting
numbers the gates no longer produce is worse than no benchmarks page, so the
snapshot is wired into the same `pytest -m eval` run that enforces the floors.

Needs an EMPTY, DISPOSABLE database, and refuses a non-local host, for the same
reason scripts/eval_report.py does.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from alembic import command  # noqa: E402
from alembic.config import Config  # noqa: E402
from sqlalchemy import create_engine, func, make_url, select  # noqa: E402
from sqlalchemy.orm import Session  # noqa: E402

from app.config import settings  # noqa: E402
from app.models import Book  # noqa: E402
from app.retrieval import DEFAULT_EMBEDDING_CANDIDATES, RRF_K, TAG_MATCH_WEIGHT  # noqa: E402
from app.synthesis import PROMPT_VERSION as SYNTHESIS_PROMPT_VERSION  # noqa: E402
from app.verification import PROMPT_VERSION as VERIFICATION_PROMPT_VERSION  # noqa: E402
from eval import judge_cases  # noqa: E402
from eval.adversarial import cases as adversarial  # noqa: E402
from eval.calibration import calibrate  # noqa: E402
from eval.cases import GOLDEN_PATH, load_cases  # noqa: E402
from eval.cassettes import CassetteJudgeClient, load_corpus  # noqa: E402
from eval.harness import load_thresholds, run_golden_set, seed_corpus  # noqa: E402
from eval.judge import PROMPT_VERSION as JUDGE_PROMPT_VERSION  # noqa: E402
from eval.judge import judge_output  # noqa: E402
from eval.metrics import aggregate, score_case  # noqa: E402

OUT_PATH = ROOT.parent / "frontend" / "app" / "benchmarks.json"
LOCAL_HOSTS = {"localhost", "127.0.0.1", "::1", "postgres", "db"}


def golden_set_section() -> dict:
    cases = [c for c in load_cases(GOLDEN_PATH) if c.expected_principle_ids]
    corpus = load_corpus()
    expected = [len(c.expected_principle_ids) for c in cases]
    return {
        "n": len(cases),
        "books": len(corpus.books),
        "principles": len(corpus.principles),
        "embedding_dimension": corpus.dimension,
        "expected_per_case_min": min(expected),
        "expected_per_case_max": max(expected),
        # Every case is an LLM paraphrase of what a real visitor typed. The page
        # says so; the field is here so it cannot be quietly dropped.
        "all_redacted": all(c.redaction == "redacted" for c in cases),
        # 0.5 / sqrt(n) as a percentage -- the standard error on a proportion at
        # its widest (p = 0.5). Printed beside every rate on the page for the
        # same reason the CLI report prints it: n=16 is small and saying so once
        # in prose is not enough.
        "standard_error_pp": round(100 * (0.25 / len(cases)) ** 0.5, 1),
    }


def retrieval_section(db: Session) -> dict:
    thresholds = load_thresholds()["retrieval"]
    top_k = thresholds["top_k"]

    current = aggregate(run_golden_set(db, top_k=top_k))

    # The honest before: what production actually returned at export time, read
    # straight out of the committed golden set. Not a re-simulation of the old
    # code -- `retrieved_at_export` is the real output, which is why the golden
    # schema keeps it strictly apart from `expected_principle_ids`. It is three
    # ids long because DEFAULT_TOP_K was 3, so it is scored at k=3: scoring it
    # at 5 would credit it with two slots it never had.
    cases = [c for c in load_cases(GOLDEN_PATH) if c.expected_principle_ids]
    baseline_k = max(len(c.retrieved_at_export) for c in cases)
    baseline = aggregate(
        [
            score_case(c.case_id, c.expected_principle_ids, c.retrieved_at_export, baseline_k)
            for c in cases
        ]
    )

    return {
        "top_k": top_k,
        "baseline_top_k": baseline_k,
        "candidates": DEFAULT_EMBEDDING_CANDIDATES,
        "tag_match_weight": TAG_MATCH_WEIGHT,
        "rrf_k": RRF_K,
        "metrics": [
            {
                "key": "recall_at_k",
                "label": f"recall@{top_k}",
                "now": current["recall_at_k"],
                "before": baseline["recall_at_k"],
                "floor": thresholds["recall_at_k_floor"],
                # Several cases expect more principles than k, so 1.0 is
                # unreachable by construction. Shipping the ceiling next to the
                # value is the difference between an honest number and a bad one.
                "ceiling": current["recall_ceiling"],
                "target": thresholds["recall_at_k_target"],
            },
            {
                "key": "precision_at_k",
                "label": f"precision@{top_k}",
                "now": current["precision_at_k"],
                "before": baseline["precision_at_k"],
                "floor": thresholds["precision_at_k_floor"],
            },
            {
                "key": "mrr",
                "label": "MRR",
                "now": current["mrr"],
                "before": baseline["mrr"],
                "floor": thresholds["mrr_floor"],
            },
            {
                "key": "hit_rate",
                "label": "hit rate",
                "now": current["hit_rate"],
                "before": baseline["hit_rate"],
                "floor": thresholds["hit_rate_floor"],
                "percent": True,
            },
        ],
        "recall_vs_ceiling": current["recall_vs_ceiling"],
    }


def verifier_section() -> dict:
    t = load_thresholds()["verifier"]
    outcomes = adversarial.run_rule_cases(adversarial.load(adversarial.RULES_PATH))
    caught, seeded = adversarial.catch_rate(outcomes)
    wrong, clean = adversarial.false_positive_rate(outcomes)
    entailment = adversarial.load(adversarial.ENTAILMENT_PATH)
    return {
        "catch_rate": round(caught / seeded, 3) if seeded else None,
        "caught": caught,
        "seeded": seeded,
        "catch_rate_floor": t["catch_rate_floor"],
        "false_positive_rate": round(wrong / clean, 3) if clean else None,
        "wrongly_rejected": wrong,
        "clean_cases": clean,
        "false_positive_rate_max": t["false_positive_rate_max"],
        "known_gaps": [o.case.case_id for o in outcomes if o.case.known_gap],
        # The entailment half needs a live provider, so it is counted here but
        # scored only in the nightly job. Saying how many cases exist stops the
        # page implying the rule half is the whole verifier.
        "entailment_cases": len(entailment),
        "prompt_version": VERIFICATION_PROMPT_VERSION,
    }


def judge_section() -> dict:
    floor = load_thresholds()["judge"]["human_kappa_floor"]
    cases = judge_cases.load()
    client = CassetteJudgeClient(settings.groq_model)
    judged = {
        c.case_id: judge_output(client, judge_cases.to_judge_input(c)).as_labels() for c in cases
    }
    results = calibrate(judge_cases.human_labels(cases), judged)
    return {
        "rubric_version": JUDGE_PROMPT_VERSION,
        "model": settings.groq_model,
        "kappa_floor": floor,
        "n": len(cases),
        "fields": [
            {
                "field": r.field,
                "kind": r.kind,
                # Four places, not three. The page displays kappa to two, and
                # rounding twice loses the half: 0.9451 -> 0.945 -> "0.94",
                # where the CLI report formats the same figure as 0.95. A
                # published number that disagrees with the report it came from
                # is a small error that looks exactly like a big one.
                "kappa": None if r.kappa is None else round(r.kappa, 4),
                "raw_agreement": round(r.raw_agreement, 4),
                "band": r.band,
            }
            for r in results
        ],
    }


def _collect_count(marker_expr: str) -> int | None:
    """How many tests a marker selects, asked of pytest rather than hardcoded.

    A test count in a committed artifact is the single most likely number to go
    quietly wrong, because nothing breaks when it does. Returns None if pytest
    cannot be run, so the page omits the figure instead of printing a stale one.
    """
    try:
        proc = subprocess.run(
            [sys.executable, "-m", "pytest", "--collect-only", "-q", "-m", marker_expr],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=180,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    # Two shapes, depending on whether the marker deselected anything:
    #   "226 tests collected in 0.4s"
    #   "15/226 tests collected (211 deselected) in 0.08s"
    for line in reversed(proc.stdout.splitlines()):
        if "tests collected" not in line and "test collected" not in line:
            continue
        head = line.strip().split()[0].split("/")[0]
        if head.isdigit():
            return int(head)
    return None


def tests_section() -> dict:
    return {
        "default": _collect_count("not eval and not eval_live"),
        "eval": _collect_count("eval"),
        "eval_live": _collect_count("eval_live"),
    }


def git_commit() -> str | None:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    return out.stdout.strip() or None


def build(db: Session, *, count_tests: bool = True) -> dict:
    return {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "commit": git_commit(),
        "prompt_versions": {
            "synthesis": SYNTHESIS_PROMPT_VERSION,
            "verification": VERIFICATION_PROMPT_VERSION,
            "judge": JUDGE_PROMPT_VERSION,
        },
        "golden_set": golden_set_section(),
        "retrieval": retrieval_section(db),
        "verifier": verifier_section(),
        "judge": judge_section(),
        "tests": tests_section() if count_tests else None,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--database-url", required=True)
    ap.add_argument("--out", default=str(OUT_PATH))
    ap.add_argument("--skip-test-counts", action="store_true")
    args = ap.parse_args()

    host = make_url(args.database_url).host or ""
    if host not in LOCAL_HOSTS and os.environ.get("LENS_ALLOW_REMOTE_TEST_DB") != "1":
        print(f"refusing to seed a non-local database host {host!r}", file=sys.stderr)
        return 2

    cfg = Config(str(ROOT / "alembic.ini"))
    cfg.cmd_opts = SimpleNamespace(x=[f"db_url={args.database_url}"])
    command.upgrade(cfg, "head")

    engine = create_engine(args.database_url)
    try:
        with Session(engine) as db:
            existing = db.scalar(select(func.count()).select_from(Book))
            if existing:
                print(
                    f"{args.database_url.rsplit('/', 1)[-1]} already contains {existing} books; "
                    "this script seeds a corpus and needs an empty database.",
                    file=sys.stderr,
                )
                return 2
            seed_corpus(db, load_corpus())
            db.commit()
            payload = build(db, count_tests=not args.skip_test_counts)
    finally:
        engine.dispose()

    out = Path(args.out)
    out.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"wrote {out}")
    print(json.dumps(payload["retrieval"]["metrics"], indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
